import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import fs from "node:fs/promises";

test("AG Studio filters persisted records, grounds evidence and answers offline without mutations", async ({ page }) => {
  test.skip(process.env.SCOPESHIELD_E2E_DAY20 !== "1", "Use the isolated --day20 runner and local-evaluation build");
  test.setTimeout(120_000);
  const errors: string[] = []; const external: string[] = []; const mutations: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.route("**/*", async (route) => {
    const host = new URL(route.request().url()).hostname;
    if (!["localhost", "127.0.0.1"].includes(host)) { external.push(host); await route.abort(); } else await route.continue();
  });
  await page.goto("/");
  await page.getByLabel("Username", { exact: true }).fill("qa.intelligence");
  await page.getByLabel("Password", { exact: true }).fill(process.env.SCOPESHIELD_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  const dashboard = page.getByRole("region", { name: "Project intelligence", exact: true });
  await expect(dashboard.getByRole("heading", { name: "SYNTHETIC - Community launch page", exact: true })).toBeVisible();
  const before = await page.evaluate(async () => (await (await fetch("http://127.0.0.1:8001/api/projects", { credentials: "include" })).json())[0]);
  page.on("request", (r) => { if (!["GET", "HEAD", "OPTIONS"].includes(r.method())) mutations.push(`${r.method()} ${new URL(r.url()).pathname}`); });
  await page.getByRole("button", { name: "Open analytics studio", exact: true }).click();
  await expect(page.locator('[data-studio-ready="true"]')).toBeVisible({ timeout: 40_000 });
  const desk = page.getByLabel("Filtered evidence review", { exact: true });
  await expect(desk.getByText(/7 linked record/)).toBeVisible();
  await fs.mkdir(process.env.SCOPESHIELD_E2E_ARTIFACTS!, { recursive: true });
  const studio = page.getByRole("region", { name: "AG Studio local evaluation", exact: true });
  await studio.evaluate((el) => el.scrollIntoView({ block: "start", behavior: "instant" }));
  await expect(studio.getByRole("button", { name: "All records", exact: true })).toBeEnabled();
  await expect(page.locator('[data-studio-rendered="true"]')).toBeVisible();
  await expect(studio.getByText("Loading...", { exact: true }).filter({ visible: true })).toHaveCount(0);
  await page.screenshot({ path: `${process.env.SCOPESHIELD_E2E_ARTIFACTS}/day20-studio-overview.png` });
  await studio.getByRole("button", { name: "Milestone", exact: true }).click();
  await expect(desk.getByText(/3 linked record/)).toBeVisible();
  const grid = studio.getByRole("grid");
  await expect(grid.getByRole("row")).toHaveCount(4); // Header + three milestones.
  const title = grid.getByRole("columnheader", { name: /title/i });
  await title.click();
  await expect(title).toHaveAttribute("aria-sort", "descending");
  await studio.getByRole("button", { name: "Scope request", exact: true }).click();
  await expect(desk.getByText(/1 linked record/)).toBeVisible();
  await expect(desk.getByRole("blockquote").first()).toBeVisible();
  await expect(desk.getByText(/extracted-text characters/).first()).toBeVisible();
  await desk.getByRole("blockquote").first().scrollIntoViewIfNeeded();
  await expect(desk.getByRole("blockquote").first()).toBeInViewport();
  await page.screenshot({ path: `${process.env.SCOPESHIELD_E2E_ARTIFACTS}/day20-studio-evidence.png` });
  await studio.getByRole("button", { name: "Sandbox invoice", exact: true }).click();
  await expect(desk.getByText(/3 linked record/)).toBeVisible();
  await expect(grid.getByText("PAID", { exact: true })).toBeVisible();
  await expect(grid.getByText("SIMULATED", { exact: true }).first()).toBeVisible();
  await studio.getByRole("button", { name: "Reset filters", exact: true }).click();
  await expect(desk.getByText(/7 linked record/)).toBeVisible();
  await desk.getByRole("button", { name: "Cross-filter selected record", exact: true }).click();
  await expect(grid.getByRole("row")).toHaveCount(2);
  await desk.getByRole("button", { name: "Clear evidence cross-filter", exact: true }).click();
  await expect(grid.getByRole("row")).toHaveCount(8);
  await studio.getByRole("button", { name: "Open offline query assistant", exact: true }).click();
  await studio.getByRole("button", { name: "Which milestones still need review?", exact: true }).click();
  await expect(studio.getByText(/2 matching record/)).toBeVisible();
  await studio.getByText(/2 matching record/).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${process.env.SCOPESHIELD_E2E_ARTIFACTS}/day20-studio-assistant.png` });
  const axe = await new AxeBuilder({ page }).include(".studio-gate").withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(axe.violations.map((v) => ({ id: v.id, targets: v.nodes.map((n) => n.target) })) ).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('[data-studio-ready="true"]')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await studio.evaluate((el) => el.scrollIntoView({ block: "start", behavior: "instant" }));
  await page.screenshot({ path: `${process.env.SCOPESHIELD_E2E_ARTIFACTS}/day20-studio-mobile.png` });
  await studio.getByRole("button", { name: "Close analytics studio", exact: true }).click();
  await expect(dashboard.getByText("Not determined", { exact: true })).toBeVisible();
  const after = await page.evaluate(async () => (await (await fetch("http://127.0.0.1:8001/api/projects", { credentials: "include" })).json())[0]);
  expect(after).toEqual(before); expect(mutations).toEqual([]); expect(external).toEqual([]); expect(errors).toEqual([]);
});

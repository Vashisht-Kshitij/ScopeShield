import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import fs from "node:fs/promises";

const artifacts = process.env.SCOPESHIELD_E2E_ARTIFACTS || "../.local/day18";
test("Evidence Pack previews a private project, downloads a PDF and preserves review state", async ({ page }) => {
  test.setTimeout(100_000);
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/demos");
  await page.getByLabel("Username", { exact: true }).fill("qa.evidence");
  await page.getByLabel("Password", { exact: true }).fill(process.env.SCOPESHIELD_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Load B · Gradual scope expansion", exact: true }).click();
  await expect(page.getByRole("region", { name: "Saved conversation" })).toBeVisible();
  await page.getByLabel("Reviewer name", { exact: true }).fill("Synthetic report reviewer");
  await page.getByLabel("Review note", { exact: true }).fill("Review before exporting the synthetic negotiation record");
  await page.getByRole("button", { name: "Analyze scope", exact: true }).click();
  await expect(page.getByText("What changed across the conversation", { exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Evidence Pack", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Evidence Pack", exact: true })).toBeVisible();
  await expect(page.getByText("Includes offline or simulated AI results; these demonstrate workflow only.", { exact: true })).toBeVisible();
  const button = page.getByRole("button", { name: "Download Evidence Pack PDF", exact: true });
  await expect(button).toBeEnabled();
  const checks = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(checks.violations.map((v) => v.id)).toEqual([]);
  await fs.mkdir(artifacts, { recursive: true });
  await page.getByRole("heading", { name: "Evidence Pack", exact: true }).scrollIntoViewIfNeeded();
  await page.locator(".evidence-pack").screenshot({ path: `${artifacts}/day18-evidence-preview.png` });
  const downloaded = page.waitForEvent("download"); await button.click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toMatch(/^scopeshield-evidence-[a-f0-9]{12}\.pdf$/);
  const path = `${artifacts}/browser-evidence-pack.pdf`; await download.saveAs(path);
  expect((await fs.readFile(path)).subarray(0, 5).toString()).toBe("%PDF-");
  await expect(page.getByText(/PDF download prepared/)).toBeVisible();
  await page.getByRole("tab", { name: "Scope changes", exact: true }).click();
  await expect(page.getByRole("button", { name: "Approve assessment", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Prepare review draft", exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("tab", { name: "Evidence Pack", exact: true }).click();
  await expect(button).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await button.scrollIntoViewIfNeeded(); await page.screenshot({ path: `${artifacts}/day18-evidence-mobile.png` });
  expect(errors).toEqual([]);
});

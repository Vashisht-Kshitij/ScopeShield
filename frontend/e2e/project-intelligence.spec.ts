import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import fs from "node:fs/promises";

const artifacts = process.env.SCOPESHIELD_E2E_ARTIFACTS || "../.local/day19";
test("project intelligence links grounded reviews and downloads a truthful executive summary", async ({ page }) => {
  test.skip(process.env.SCOPESHIELD_E2E_DAY19 !== "1", "Run the isolated Day 19 fixture runner");
  test.setTimeout(100_000);
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.getByLabel("Username", { exact: true }).fill("qa.intelligence");
  await page.getByLabel("Password", { exact: true }).fill(process.env.SCOPESHIELD_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  const dashboard = page.getByRole("region", { name: "Project intelligence", exact: true });
  await expect(dashboard.getByRole("heading", { name: "SYNTHETIC - Community launch page", exact: true })).toBeVisible();
  await expect(dashboard.getByText("SIMULATED — NO REAL PAYMENT", { exact: true }).first()).toBeVisible();
  await expect(dashboard.getByText("USD 3.00", { exact: true }).first()).toBeVisible();
  await expect(dashboard.getByText("USD 1.00", { exact: true }).first()).toBeVisible();
  await expect(dashboard.getByText("Not determined", { exact: true })).toBeVisible();
  await expect(dashboard.getByText("1 record(s) · provider PAID", { exact: true })).toBeVisible();
  await expect(dashboard.getByText("Local creation state: CREATED", { exact: true }).first()).toBeVisible();
  const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(axe.violations.map((v) => v.id)).toEqual([]);
  await fs.mkdir(artifacts, { recursive: true });
  await dashboard.screenshot({ path: `${artifacts}/day19-project-overview.png` });
  await dashboard.getByRole("link", { name: "Synthetic launch conversation", exact: true }).first().click();
  await expect(page.getByRole("region", { name: "Saved conversation", exact: true })).toBeVisible();
  await expect(page.getByText("Offline / mocked response", { exact: true })).toBeVisible();
  await page.getByRole("region", { name: "Saved conversation", exact: true }).screenshot({ path: `${artifacts}/day19-conversation.png` });
  await page.getByText("What changed across the conversation", { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${artifacts}/day19-cumulative-findings.png` });
  await page.getByRole("tab", { name: "Change orders", exact: true }).click();
  await expect(page.getByLabel("Proposed additional deliverables", { exact: true })).toHaveValue("SYNTHETIC PROPOSAL: separate ticket-checkout work; support hours require negotiation");
  await page.locator(".order-panel").screenshot({ path: `${artifacts}/day19-proposed-order.png` });
  await page.getByRole("tab", { name: "Project overview", exact: true }).click();
  await expect(dashboard.getByRole("heading", { name: "SYNTHETIC - Community launch page", exact: true })).toBeVisible();
  const before = await page.evaluate(async () => (await (await fetch("http://127.0.0.1:8001/api/projects", { credentials: "include" })).json())[0]);
  await page.getByRole("tab", { name: "Evidence Pack", exact: true }).click();
  const button = page.getByRole("button", { name: "Download executive summary", exact: true });
  await expect(button).toBeEnabled();
  const downloadEvent = page.waitForEvent("download"); await button.click();
  const download = await downloadEvent; expect(download.suggestedFilename()).toMatch(/^scopeshield-summary-[a-f0-9]{12}\.pdf$/);
  await download.saveAs(`${artifacts}/browser-executive-summary.pdf`);
  await expect(page.getByText(/PDF download prepared/)).toBeVisible();
  const after = await page.evaluate(async () => (await (await fetch("http://127.0.0.1:8001/api/projects", { credentials: "include" })).json())[0]);
  expect(after).toEqual(before);
  await page.getByRole("tab", { name: "Project overview", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(dashboard.getByText("Not determined", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await dashboard.screenshot({ path: `${artifacts}/day19-project-mobile.png` });
  expect(errors).toEqual([]);
});

import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

test("HTTPS judge login, offline review, isolation and actual API restart", async ({ page, context }) => {
  const output = process.env.SCOPESHIELD_E2E_ARTIFACTS!;
  await page.goto("/");
  await page.getByLabel("Username", { exact: true }).fill("judge.one");
  await page.getByLabel("Password", { exact: true }).fill(process.env.SCOPESHIELD_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByText(/Judge demo · Synthetic examples/)).toBeVisible();
  await expect(page.getByText("Synthetic judge workspace", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Open analytics studio", exact: true })).not.toBeAttached();
  await expect(page.getByRole("link", { name: "API documentation" })).not.toBeAttached();
  const session = (await context.cookies()).find((cookie) => cookie.name === "scopeshield_session")!;
  expect(session.secure && session.httpOnly && session.sameSite === "Strict").toBe(true);
  const checks = await page.evaluate(async () => {
    const me = await (await fetch("/api/auth/me")).json();
    const rows = await (await fetch("/api/contracts")).json();
    const cid = rows[0].id;
    const noCsrf = await fetch(`/api/contracts/${cid}/extract`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ mode: "offline_demo" }) });
    const configured = await fetch(`/api/contracts/${cid}/extract`, { method: "POST", headers: { "Content-Type": "application/json", "X-CSRF-Token": me.csrf_token }, body: JSON.stringify({ mode: "configured" }) });
    return { cid, noCsrf: noCsrf.status, configured: configured.status, docs: (await fetch("/docs")).status };
  });
  expect(checks.noCsrf).toBe(403); expect(checks.configured).toBe(403); expect(checks.docs).toBe(404);
  await page.goto(`/contracts/${checks.cid}`);
  await page.getByRole("button", { name: "Extract agreement", exact: true }).click();
  await page.getByRole("button", { name: "Run extraction", exact: true }).click();
  await expect(page.getByText("Offline / mocked extraction", { exact: true }).first()).toBeVisible();
  await expect(page.getByRole("heading", { name: "Extracted agreement text" })).toBeVisible();
  const axe = await new AxeBuilder({ page }).analyze();
  fs.writeFileSync(path.join(output, "axe-https.json"), JSON.stringify(axe));
  expect(axe.violations).toEqual([]);
  await page.screenshot({ path: path.join(output, "https-judge-workspace.png"), fullPage: true });
  const pdf = fs.readFileSync(path.join(output, "synthetic-agreement.pdf"));
  const uploaded = await page.evaluate(async (bytes) => {
    const me = await (await fetch("/api/auth/me")).json();
    const form = new FormData(); form.append("file", new Blob([new Uint8Array(bytes)], { type: "application/pdf" }), "synthetic-agreement.pdf");
    const response = await fetch("/api/contracts", { method: "POST", headers: { "X-CSRF-Token": me.csrf_token }, body: form });
    if (response.status !== 201) throw new Error(`PDF upload failed: ${response.status}`);
    return response.json();
  }, [...pdf]);
  expect(uploaded.pdf_provenance.pages.length).toBe(2);
  await page.goto(`/contracts/${uploaded.id}`);
  await page.getByRole("button", { name: "Extract agreement", exact: true }).click();
  await page.getByRole("button", { name: "Run extraction", exact: true }).click();
  await expect(page.getByText("Offline / mocked extraction", { exact: true }).first()).toBeVisible();
  await page.getByRole("group", { name: "Select milestone" }).getByRole("button").last().click();
  await page.getByRole("button", { name: "Locate in agreement" }).first().click();
  await expect(page.getByText("Original PDF physical page: 2", { exact: true })).toBeVisible();
  const downloading = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download original PDF" }).click();
  const download = await downloading;
  const downloadedPath = path.join(output, "downloaded-original.pdf");
  await download.saveAs(downloadedPath);
  expect(createHash("sha256").update(fs.readFileSync(downloadedPath)).digest("hex")).toBe(uploaded.sha256);
  const pdfAxe = await new AxeBuilder({ page }).analyze();
  fs.writeFileSync(path.join(output, "axe-pdf.json"), JSON.stringify(pdfAxe));
  expect(pdfAxe.violations).toEqual([]);
  await page.screenshot({ path: path.join(output, "https-pdf-evidence.png"), fullPage: true });
  await page.goto(`/contracts/${checks.cid}`);
  fs.writeFileSync(path.join(output, "restart-request.json"), "{}");
  await expect.poll(() => fs.existsSync(path.join(output, "restart-complete.json"))).toBe(true);
  await expect.poll(async () => page.evaluate(async () => { try { return (await fetch("/api/auth/me")).status; } catch { return 0; } })).toBe(200);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Extracted agreement text" })).toBeVisible();
  const persisted = await page.evaluate(async (cid) => (await (await fetch(`/api/contracts/${cid}`)).json()).milestones.length, checks.cid);
  expect(persisted).toBe(3);
  // Chrome owns the isolated DNS mapping; Node's request client must not bypass it.
  const originalAfterRestart = await page.evaluate(async (cid) => {
    const response = await fetch(`/api/contracts/${cid}/original`);
    const digest = await crypto.subtle.digest("SHA-256", await response.arrayBuffer());
    return { status: response.status, sha256: Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("") };
  }, uploaded.id);
  expect(originalAfterRestart.status).toBe(200);
  expect(originalAfterRestart.sha256).toBe(uploaded.sha256);
  const separate = await context.browser()!.newContext({ baseURL: "https://demo.example.test", ignoreHTTPSErrors: true });
  const other = await separate.newPage();
  await other.goto("/");
  await other.getByLabel("Username", { exact: true }).fill("judge.two");
  await other.getByLabel("Password", { exact: true }).fill(process.env.SCOPESHIELD_E2E_PASSWORD!);
  await other.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(other.getByText(/Judge demo · Synthetic examples/)).toBeVisible();
  expect(await other.evaluate(async (cid) => (await fetch(`/api/contracts/${cid}`)).status, checks.cid)).toBe(404);
  expect(await other.evaluate(async (cid) => (await fetch(`/api/contracts/${cid}/original`)).status, uploaded.id)).toBe(404);
  const prepared = await other.evaluate(async () => {
    const rows = await (await fetch("/api/contracts")).json();
    return (await fetch(`/api/contracts/${rows[0].id}`)).json();
  });
  expect(prepared.milestones.length).toBe(3);
  await other.goto(`/contracts/${prepared.id}`);
  await expect(other.getByRole("group", { name: "Select milestone" }).getByRole("button")).toHaveCount(3);
  await other.getByRole("tab", { name: "Scope changes", exact: true }).click();
  for (const label of ["In scope", "Out of scope", "Ambiguous"]) await expect(other.getByText(label, { exact: true })).toBeVisible();
  await other.getByRole("tab", { name: "Invoices" }).click();
  await expect(other.getByRole("heading", { name: "Simulated invoice history" })).toBeVisible();
  await expect(other.getByText("Paid example · SIMULATED", { exact: true })).toBeVisible();
  await expect(other.getByRole("button", { name: "Preview invoice draft" })).not.toBeAttached();
  const simulatedAxe = await new AxeBuilder({ page: other }).analyze();
  fs.writeFileSync(path.join(output, "axe-simulated-history.json"), JSON.stringify(simulatedAxe));
  expect(simulatedAxe.violations).toEqual([]);
  await other.screenshot({ path: path.join(output, "prepared-judge-simulated-history.png"), fullPage: true });
  await separate.close();
  fs.writeFileSync(path.join(output, "https-checks.json"), JSON.stringify({ ...checks, secureCookie: true, otherJudgeDenied: true, persistedMilestones: persisted, pdfId: uploaded.id, originalSha256: uploaded.sha256, pdfPage: 2, originalSurvivedRestart: true, preparedJudgeMilestones: 3, simulatedHistory: true, axeViolations: axe.violations.length + pdfAxe.violations.length + simulatedAxe.violations.length }));
});
